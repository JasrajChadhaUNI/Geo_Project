def finish_manifest(p, cases):
    """Record every exported figure and its interpretation for report assembly."""
    captions = {
        "01_pipeline": "Whole analysis pipeline. GNS references evaluate predictions and do not train or alter them.",
        "02_sh1_north_context": "SH1 North road inspection categories over current OpenStreetMap context. Green is not confirmed open. Coordinates EPSG:2193; scale bar in kilometres. © OpenStreetMap contributors, ODbL.",
        "02_sh1_south_context": "SH1 South road inspection categories over current OpenStreetMap context. Grey denotes insufficient observation where proximity categories do not apply. © OpenStreetMap contributors, ODbL.",
        "02_route70_context": "Assessed Route 70 corridor over current OpenStreetMap context; not the entire historic relief route. © OpenStreetMap contributors, ODbL.",
        "03_point_validation": "GNS V2 point matching uses observable source points as denominator. Coverage is shown separately. It does not measure false-positive precision.",
        "04_threshold_sensitivity": "Changing the threshold changes point matching and the spatial union of candidates. Union area removes overlap between road families; it is not confirmed landslide area or confined to the 1 km evaluation buffer.",
        "05_observation_timing": "Actual post-event acquisition delays per processing tile, not elapsed model runtime. The map combines multiple dates.",
    }
    for case in cases:
        captions[case["tile_id"]] = (
            case["caption"]
            + f" Before: {case['pre']}; after: {case['post']}. Same 2.56 km square in each panel, north up. Copernicus Sentinel-2; roads © OpenStreetMap contributors; GNS reference sources."
        )
    records = []
    for folder in [p.out / "figures", p.out / "evidence"]:
        for f in sorted(folder.glob("*.png")):
            records.append(
                dict(
                    file=str(f.relative_to(p.out)),
                    caption=captions.get(f.stem, ""),
                    dpi=300,
                )
            )
    dump(p.out / "figure_manifest.json", records)
    (p.out / "FIGURE_CAPTIONS.md").write_text(
        "\n\n".join(f"**{r['file']}**\n\n{r['caption']}" for r in records) + "\n"
    )
    return records
